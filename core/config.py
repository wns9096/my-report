def word(kind, key, default=None):
    """PROPOSAL_WORDS 에서 인쇄용 말을 꺼낸다.

    없는 키가 와도 멈추지 않는다 — 키를 그대로 쓴다. 말이 없다고 문서가
    안 나오면, 말을 정하려고 문서를 못 보는 일이 생긴다.
    """
    return PROPOSAL_WORDS.get(kind, {}).get(key, default if default is not None else key)
