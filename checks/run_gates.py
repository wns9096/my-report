def fill(at, key, value):
    for t in at.text_area:
        if t.key == key:
            t.set_value(value)
            return True
    return False


def click(at, key):
    for b in at.button:
        if b.key == key:
            if b.disabled:
                return "잠김"
            b.click()
            at.run()
            return "눌림"
    return "없음"


